def _resolve_ref(ref_llm):
    """This gate's reference per case: the cached plain-forward run where that is the
    anchor, the cached original where one exists, else a live run over ``ref_llm``."""
    live = live_ref_factory(ref_llm)

    def resolve(case, seed, make, mkc):
        if case.reference == "ref":
            return _ref(case.label, case.n_particles, case.ess, case.max_tokens, seed)
        if case.reference == "forward_cached":
            return _forward_cached(
                case.label, case.n_particles, case.ess, case.max_tokens, seed
            )
        return live(case, seed, make, mkc)

    return resolve


def _nobias(label, llm, ref_llm, **kwargs):
    """Drive a homogeneous CASES no-bias case against this gate's references."""
    return assert_case_unbiased(
        CASES[label], llm, PROMPT, _resolve_ref(ref_llm), **kwargs
    )


