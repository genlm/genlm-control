# ----- gate 2g: multi-view (proposal q + prior p0, two views on one engine) -------
#
# K=2 multi-view: DirectTokenSampler(potential=p0, proposal=q) where q and p0 are two
# PromptedLLMs on the SAME engine (here differing by prompt; the LoRA case differs by
# adapter -- same control path). Draws come from q and are reweighted by p0/q.


def test_multiview_proposal_unbiased(llm, ref_llm):
    """Two prompt-views q/p0 on one engine -> K=2 multi-view; unbiased log_ml vs plain
    forwards across seeds. Exercises the multi-view machinery: two logit views per step,
    p0/q reweight, one drawn token advancing both."""
    def make(m):
        q = PromptedLLM(
            m.model,
            prompt_ids=m.model.tokenizer.encode("Once upon a"),
            eos_byte_strings=EOS_BYTES,
        )
        p0 = PromptedLLM(
            m.model,
            prompt_ids=m.model.tokenizer.encode(PROMPT),
            eos_byte_strings=EOS_BYTES,
        )
        return DirectTokenSampler(potential=p0, proposal=q)

    # The K=2 multiview log_ml estimator is high-variance: a flat proposal ("Once upon a")
    # makes the engine's draws diverge from the reference's on many tokens, and N=8 marginal
    # likelihood swings hard per seed (range ~+-10). The run is unbiased over the seeds
    # (mean ~0), but a 6-seed mean is brittle -- a tiny draw change tips it past 2.5*sem.
    # Average over enough seeds that the unbiasedness check is robust (and more sensitive to
    # a real bias, not less).
    seeds = tuple(range(24))
    diffs = []
    for seed in seeds:
        ref = run_case(lambda: make(ref_llm), 8, 0.0, 10, seed)
        run = run_case(lambda: make(llm), 8, 0.0, 10, seed)
        s = compare_runs("multiview-q/p0", 0.0, 8, ref, run)
        diffs.append(s["log_ml_diff"])
    diffs = np.array(diffs)
    sem = diffs.std() / np.sqrt(len(diffs))
    print(
        f"\nmultiview q/p0 over {len(seeds)} seeds: "
        f"log_ml diff mean={diffs.mean():+.4f} sem={sem:.4f}"
    )
    assert abs(diffs.mean()) <= max(0.3, 2.5 * sem), (
        f"multiview log_ml biased: mean {diffs.mean():+.4f} (sem {sem:.4f})"
    )


def test_batched_multiview_unbiased(llm, ref_llm):
    """B>1 groups, each a K=2 multi-view (q proposal + p0 prior, group-specific prompts),
    run as ONE batched population. Per-group log_ml unbiased vs a single-run plain-forward
    reference of each group: group and view are orthogonal, so there is no cross-group
    coupling."""
    from genlm.control.sampler.sequence import SMC

    prompts = ["The", "Once upon a", "In the", "A B C", "Hello world", "To be"]
    B = len(prompts)

    def make_group(m, p):
        q = PromptedLLM(
            m.model,
            prompt_ids=m.model.tokenizer.encode(p + " then"),
            eos_byte_strings=EOS_BYTES,
        )
        p0 = PromptedLLM(
            m.model, prompt_ids=m.model.tokenizer.encode(p), eos_byte_strings=EOS_BYTES
        )
        return DirectTokenSampler(potential=p0, proposal=q)

    refs = np.array(
        [
            run_case(lambda pp=p: make_group(ref_llm, pp), 8, 0.0, 10, SEED)["log_ml"]
            for p in prompts
        ]
    )

    seed_all(SEED)
    smcs = [SMC(make_group(llm, p)) for p in prompts]
    seqs = asyncio.run(
        SMC.batched(smcs, n_particles=8, ess_threshold=0.0, max_tokens=10)
    )
    assert len(seqs) == B, f"SMC.batched returned {len(seqs)} groups, expected {B}"

    run = np.array([s.log_ml for s in seqs])
    fb, fr = run[np.isfinite(run)], refs[np.isfinite(refs)]
    diff = fb.mean() - fr.mean()
    sem = np.sqrt(fb.std() ** 2 / max(len(fb), 1) + fr.std() ** 2 / max(len(fr), 1))
    print(
        f"\nbatched multiview B={B} K=2: run mean={fb.mean():+.4f} "
        f"ref mean={fr.mean():+.4f} diff={diff:+.4f} sem={sem:.4f}"
    )
    assert abs(diff) <= max(0.3, 3.0 * sem), (
        f"batched multiview log_ml biased vs single-run forwards: "
        f"diff {diff:+.4f} (sem {sem:.4f})"
    )


