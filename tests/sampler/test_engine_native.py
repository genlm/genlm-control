# ----- gate 2h: SMC.batched (B groups in ONE population) ----------------------
#
# SMC.batched runs B examples as ONE population (B groups of n_particles); ESS / resample /
# log_ml are group-local, so each group must be statistically identical to running it alone.
# The comparison is paired at the same seed (both sides draw all groups under the same
# shared stream in the same order), so MC variance cancels and a B>1 bug shows as a
# persistent same-sign group-mean gap. (Comparing the batched group-mean against the cached
# SINGLE-run references is the wrong gauge: those are 12 high-variance short-sequence runs
# whose mean sits ~1 log_ml off the true value, so the difference is dominated by reference
# noise, not bias. The batched MATH itself -- B groups in one population == B solo runs, no
# cross-group coupling -- is gate-1's byte-exact per-group pinning, not this test's job.)


def test_batched_smc_unbiased(llm, ref_llm):
    """B homogeneous groups in one batched population, engine-served vs plain forwards.
    Each pop-seed gives one paired group-mean log_ml diff; the mean across seeds is
    unbiased (~0). A persistent same-sign gap is a bug."""
    from genlm.control.sampler.sequence import SMC

    llm.set_prompt_from_str(PROMPT)
    target = boolfsa(llm, r"[aeiou ]+")
    ref_target = boolfsa(ref_llm, r"[aeiou ]+")
    pop_seeds = (1234, 7, 99, 2024, 555, 31, 808, 42, 17, 6, 71, 900)
    B = len(pop_seeds)

    def group_mean(seed, tgt):
        seed_all(seed)
        smcs = [SMC(DirectTokenSampler(tgt)) for _ in range(B)]
        seqs = asyncio.run(
            SMC.batched(smcs, n_particles=16, ess_threshold=0.5, max_tokens=10)
        )
        assert len(seqs) == B, f"SMC.batched returned {len(seqs)} groups, expected {B}"
        mls = np.array([s.log_ml for s in seqs])
        return mls[np.isfinite(mls)].mean()

    diffs = []
    for s in pop_seeds:
        t0 = time.perf_counter()
        run = group_mean(s, target)
        ref = group_mean(s, ref_target)
        diffs.append(run - ref)
        log(
            f"SMC.batched B={B} seed={s}: {time.perf_counter() - t0:.1f}s  "
            f"run group-mean={run:+.4f} ref={ref:+.4f} diff={run - ref:+.4f}"
        )
    diffs = np.array(diffs)
    sem = diffs.std() / np.sqrt(len(diffs))
    log(
        f"SMC.batched run-vs-forwards (paired): group-mean log_ml diff "
        f"mean={diffs.mean():+.4f} sem={sem:.4f}"
    )
    assert abs(diffs.mean()) <= max(0.4, 3.0 * sem), (
        f"batched group-mean log_ml biased vs plain forwards: "
        f"mean diff {diffs.mean():+.4f} (sem {sem:.4f})"
    )


def test_batched_per_group_lm_critic_unbiased(llm, ref_llm):
    """B groups carrying DISTINCT token-grain LM critics (own prompt each). Every row must
    be scored by ITS group's critic, not group 0's. Group-mean log_ml stays unbiased vs
    plain forwards."""
    from genlm.control.sampler.sequence import SMC

    hints = ("It is known that", "Consider instead", "Recall the fact that")
    B = len(hints)
    seeds = (1234, 7, 99, 2024, 555, 31, 42, 271, 828, 1618,
             6, 71, 900, 17, 808, 2718, 3141, 5772, 88, 909)

    def make_critics(m):
        return [
            PromptedLLM(
                m.model,
                prompt_ids=m.model.tokenizer.encode(hint),
                eos_byte_strings=EOS_BYTES,
            )
            for hint in hints
        ]

    llm.set_prompt_from_str(PROMPT)
    critics = make_critics(llm)
    ref_critics = make_critics(ref_llm)

    def group_mean(seed, m, cs):
        seed_all(seed)
        smcs = [SMC(DirectTokenSampler(m), critic=c) for c in cs]
        seqs = asyncio.run(
            SMC.batched(smcs, n_particles=8, ess_threshold=0.5, max_tokens=8)
        )
        assert len(seqs) == B, f"SMC.batched returned {len(seqs)} groups, expected {B}"
        mls = np.array([s.log_ml for s in seqs])
        return mls[np.isfinite(mls)].mean()

    # An LM critic twist over a short horizon resamples hard, so a single paired diff
    # runs to several nats; the seed count is what makes the mean a usable statistic.
    diffs = []
    for s in seeds:
        t0 = time.perf_counter()
        run = group_mean(s, llm, critics)
        ref = group_mean(s, ref_llm, ref_critics)
        diffs.append(run - ref)
        log(
            f"per-group LM critic B={B} seed={s}: {time.perf_counter() - t0:.1f}s  "
            f"run group-mean={run:+.4f} ref={ref:+.4f} diff={run - ref:+.4f}"
        )
    diffs = np.array(diffs)
    sem = diffs.std() / np.sqrt(len(diffs))
    log(
        f"batched per-group LM critic (paired): group-mean log_ml diff "
        f"mean={diffs.mean():+.4f} sem={sem:.4f}"
    )
    assert abs(diffs.mean()) <= max(0.4, 3.0 * sem), (
        f"per-group LM critic group-mean log_ml biased: "
        f"mean diff {diffs.mean():+.4f} (sem {sem:.4f})"
    )
