"""Gate-2 on vLLM: SMC served by the vLLM engine is UNBIASED vs the same cases served by
plain per-context forwards.

Byte-exactness is impossible here -- the engine reads warm-KV decode logits instead of
re-prefilling every step, a ~1e-2/logit residual that may flip a Gumbel-max draw -- so each
test averages the run-vs-reference log_ml (and length) diff across seeds and asserts the
MEAN sits within sampling noise of 0 (``_harness.assert_unbiased``). A consistent same-sign
gap is a BUG, not a tolerance.

Two cached references, chosen per case (the ``reference`` field of ``gate2_cases.CASES``):
- ``"forward_cached"`` -- plain per-context forwards under the counter-based picker, cached
  in ``gate2_forward_snapshot.json`` by ``gen_reference.py``. RNG-matched to this run, so
  the paired diff is tight (engine numeric residual only).
- ``"ref"`` -- the genuine ORIGINAL genlm-control (main + llamppl ``smc_standard``), cached
  in ``gate2_snapshot.json`` by ``gen_original_reference.py``. The independent anchor.
Any other value resolves live over ``ref_llm``, a second backend. A missing cached key is a
hard error (run the generator) -- never a silent self-comparison.

Config (seeds/N/ess/critics/samplers) and the shared critics live in ``gate2_cases.py``,
imported by BOTH this gate and the generators so they cannot drift; the seed/serialization/
no-bias-assert harness is ``_harness.py`` (shared with gate-1).

**Regenerate the cached original** (after changing a ``"ref"`` config) on the box, shadowing
our genlm.control with main's::

    PYTHONPATH=/root/genlm/genlm-control-main VLLM_USE_FLASHINFER_SAMPLER=0 \\
        /root/genlm-venv/bin/python tests/sampler/gen_original_reference.py

Requires CUDA + vLLM; uses gpt2. Run on the box with ``VLLM_USE_FLASHINFER_SAMPLER=0``.
"""

